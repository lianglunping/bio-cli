class Error(Exception):
    pass


def tool(name):
    # Site-local configuration is generated by the installer, never distributed.
    config = Path(__file__).resolve().parent / 'runtime.json'
    mapping = json.loads(config.read_text()) if config.exists() else {}
    result = mapping.get(name) or shutil.which(name)
    if not result or not os.access(result, os.X_OK):
        raise Error('Missing dependency: ' + name + '; install it in a personal environment')
    return result


def regular(value):
    p = Path(value).absolute()
    if not p.is_file():
        raise Error('Not a readable regular file: ' + str(p))
    return p


def compression(path):
    with path.open('rb') as f:
        magic = f.read(6)
    if magic.startswith(b'\x1f\x8b'): return 'gzip'
    if magic.startswith(b'\x28\xb5\x2f\xfd'): return 'zstd'
    if magic.startswith(b'BZh'): return 'bzip2'
    if magic.startswith(b'\xfd7zXZ\x00'): return 'xz'
    return None


def container_format(path):
    # Never pass arbitrary data to bsdtar: it also recognizes filesystem manifests.
    with path.open('rb') as stream:
        magic = stream.read(8)
    signatures = {'rar': (b'Rar!\x1a\x07\x00', b'Rar!\x1a\x07\x01\x00'),
                  '7z': (b'7z\xbc\xaf\x27\x1c',),
                  'zip': (b'PK\x03\x04', b'PK\x05\x06')}
    for fmt, prefixes in signatures.items():
        if magic.startswith(prefixes):
            return fmt
    return None


class Reader:
    """Bounded diagnostic capture; timeout applies to the owned backend group."""
    def __init__(self, path, command=None, env=None, timeout=None):
        if command is None:
            c = compression(path)
            if c:
                command = [tool(c), '-dc', str(path)]
        self.truncated = False
        self.process = None
        if command:
            self.process = ManagedProcess(command, env=env, timeout=timeout)
            self.stream = self.process.stdout
        else:
            self.stream = path.open('rb')

    def close(self, cancel=False):
        try:
            self.stream.close()
        finally:
            if self.process:
                code = self.process.finish(cancel=cancel, wait_timeout=5)
                message = bytes(self.process.errors.data).decode('utf-8', 'replace').strip()
                if self.process.errors.truncated:
                    message += '\n[backend diagnostics truncated]'
                if code and not cancel:
                    raise Error(message or 'Reader failed with exit code ' + str(code))


@contextlib.contextmanager
def reader(path, command=None, env=None, timeout=None):
    r = Reader(path, command, env, timeout)
    try:
        yield r
    except BaseException:
        r.close(cancel=True)
        raise
    else:
        r.close(cancel=r.truncated)


def iter_tar(archive):
    # Explicit next() avoids retaining TarInfo for every earlier file. extractfile
    # receives the current regular TarInfo; links are handled by our own policy.
    while True:
        member = archive.next()
        if member is None:
            break
        archive.members.clear()
        yield member



def safe_text(data):
    # Escape terminal controls while preserving tabs, newlines and UTF-8.
    text = data.decode('utf-8', 'replace')
    # Scan ordinary text in the regex engine; Python runs only for controls found.
    return CONTROLS.sub(lambda match: '\\x%02x' % ord(match.group()), text)


def preview_stream(r, lines, byte_limit):
    output = bytearray()
    for _ in range(lines):
        remaining = byte_limit - len(output)
        if remaining <= 0:
            r.truncated = True; break
        chunk = r.stream.readline(remaining)
        if not chunk: break
        output.extend(chunk)
    else:
        r.truncated = True
    if len(output) >= byte_limit: r.truncated = True
    if b'\x00' in output:
        return 'Metadata only: binary content detected; use a format-specific reader\n'
    return safe_text(bytes(output))


def display(text, no_pager):
    if sys.stdout.isatty() and not no_pager and shutil.which('less'):
        env = os.environ.copy()
        env['LESSSECURE'] = '1'
        p = subprocess.Popen([shutil.which('less'), '-F', '-S', '-X'], stdin=subprocess.PIPE, env=env)
        try:
            p.communicate(text.encode('utf-8'))
        except BrokenPipeError:
            p.wait()
    else:
        sys.stdout.write(text)


def peek(args):
    path = regular(args.input)
    name = path.name.lower()
    if name.endswith(INDEX + SPECIAL):
        print(safe_text(('Metadata only: %s\nSize: %d bytes\nClass: %s' % (path.name, path.stat().st_size, 'binary index' if name.endswith(INDEX) else 'specialized binary format')).encode('utf-8', 'replace')))
        return
    fmt = container_format(path)
    if fmt is None and name.endswith(('.rar', '.7z')):
        raise Error('Invalid or unsupported archive signature: ' + path.name)
    if fmt in ('rar', '7z'):
        with reader(path, [tool('bsdtar'), '-tf', str(path)], timeout=args.timeout) as r:
            listing = preview_stream(r, args.lines, args.max_bytes)
            truncated = r.truncated
        display(listing, args.no_pager)
    elif fmt == 'zip' or name.endswith('.zip'):
        with zipfile.ZipFile(path) as z:
            result = bytearray()
            truncated = False
            for i, member in enumerate(z.infolist()):
                row = ('%d\t%s\n' % (member.file_size, member.filename)).encode()
                if i >= args.lines or len(result) + len(row) > args.max_bytes:
                    truncated = True; break
                result.extend(row)
        display(safe_text(result), args.no_pager)
    elif name.endswith(ARCHIVES):
        result = bytearray(); truncated = False
        with reader(path, timeout=getattr(args, 'timeout', None)) as r:
            with tarfile.open(fileobj=r.stream, mode='r|') as archive:
                for i, member in enumerate(iter_tar(archive)):
                    row = ('%d\t%s\n' % (member.size, member.name)).encode()
                    if i >= args.lines or len(result) + len(row) > args.max_bytes:
                        r.truncated = truncated = True; break
                    result.extend(row)
                    # Asking for the next header skips the current member's payload.
                    # Stop now, before a large FASTQ/BAM is read just to discover N+1.
                    if i + 1 >= args.lines or len(result) >= args.max_bytes:
                        r.truncated = truncated = True; break
            # tar end markers can precede a compressed checksum; drain to verify it.
            if not r.truncated:
                while r.stream.read(65536): pass
        display(safe_text(result), args.no_pager)
    else:
        command = None
        env = None
        if name.endswith(('.bam', '.cram')):
            command = [tool('samtools'), 'view', '--no-PG', '-H' if args.header else '-h']
            if name.endswith('.cram') and not args.header:
                if not args.reference:
                    raise Error('CRAM record preview requires --reference <local.fa>; use --header for header only')
                reference = regular(args.reference)
                if not Path(str(reference) + '.fai').is_file():
                    raise Error('Reference .fai must already exist; peek never creates an index')
                command += ['-T', str(reference)]
                env = os.environ.copy(); env['REF_PATH'] = str(reference.parent); env['REF_CACHE'] = ''
            command.append(str(path))
        elif name.endswith('.bcf'):
            command = [tool('bcftools'), 'view', '--no-version', '-h' if args.header else '-Ov', str(path)]
        elif args.header:
            raise Error('--header is supported for BAM, CRAM and BCF; use -n for text formats')
        with reader(path, command, env, getattr(args, 'timeout', None)) as r:
            text = preview_stream(r, args.lines, args.max_bytes)
            truncated = r.truncated
        display(text, args.no_pager)
    if truncated:
        print('peek: preview limit reached; this is not a complete integrity check', file=sys.stderr)


def compressor(fmt, threads, level):
    if fmt == 'zstd': return [tool('zstd'), '-q', '-c', '-T' + str(threads), '-' + str(level)]
    if fmt == 'gzip': return [tool('gzip'), '-c', '-n', '-' + str(min(level, 9))]
    if fmt in ('xz', 'bzip2'):
        return [tool(fmt), '-c', '-' + str(min(level, 9))] + (['-T' + str(threads)] if fmt == 'xz' else [])
    return [tool('bgzip'), '-c', '-@', str(threads), '-l', str(min(level, 9))]


def publish(partial, target):
    # Atomic no-clobber publication on the same filesystem.
    os.link(str(partial), str(target))
    partial.unlink()


def validate_pack_tree(source, portable=False):
    """Reject members our safe restore cannot reproduce; never follow links."""
    root = source.resolve()
    member_path(source.name)
    if source.name == '.bio-cli-incomplete':
        raise Error('Source name conflicts with the restore status marker')
    def check(path):
        member_path(str(path.relative_to(source)))
        mode = path.lstat().st_mode
        if stat.S_ISLNK(mode):
            if portable:
                raise Error('Use tar to archive symbolic links: ' + str(path))
            value = os.readlink(path)
            if os.path.isabs(value):
                raise Error('Directory contains an absolute symbolic link: ' + str(path))
            target = (path.parent / value).resolve()
            if target != root and root not in target.parents:
                raise Error('Directory contains an escaping symbolic link: ' + str(path))
        elif not (stat.S_ISREG(mode) or stat.S_ISDIR(mode)):
            raise Error('Directory contains an unsupported special member: ' + str(path))
    def fail(exc):
        raise exc
    for parent, directories, files in os.walk(source, followlinks=False, onerror=fail):
        for name in directories + files:
            check(Path(parent) / name)


STREAM_SUFFIX = {'gzip': '.gz', 'xz': '.xz', 'zstd': '.zst', 'bzip2': '.bz2', 'bgzip': '.gz'}
TAR_CODEC = {'tar.gz': 'gzip', 'tar.xz': 'xz', 'tar.bz2': 'bzip2', 'tar.zst': 'zstd'}


def checked_backend(command, **kwargs):
    process = ManagedProcess(command, **kwargs)
    if process.finish():
        raise Error(process.errors.data.decode('utf-8', 'replace').strip() or ('%s failed with exit code %d' % (Path(command[0]).name, process.proc.returncode)))


def pack_container(source, target, fmt, level):
    native = tool('rar' if fmt == 'rar' else 'bsdtar')
    if fmt == 'rar' and any(char in source.name for char in '*?'):
        raise Error('RAR input name contains a wildcard')
    member_path(source.name)
    if source.name == '.bio-cli-incomplete':
        raise Error('Source name conflicts with the restore status marker')
    staging = Path(tempfile.mkdtemp(prefix=target.name + '.partial-', dir=str(target.parent)))
    partial = staging / ('archive.' + fmt)
    before = source.stat()
    try:
        operand = './' + source.name
        if fmt == 'rar':
            checked_backend([native, 'a', '-cfg-', '-idq', '-ma5', '-m' + str(min(level, 5)),
                             '--', str(partial), operand], cwd=source.parent, stdout=subprocess.DEVNULL)
            check = [native, 't', '-cfg-', '-idq', '-p-', '--', str(partial)]
        else:
            command = [native, '-cf', str(partial), '--format', '7zip' if fmt == '7z' else fmt,
                       '--options', 'compression-level=' + str(min(level, 9)), '--', operand]
            checked_backend(command, cwd=source.parent, stdout=subprocess.DEVNULL,
                            env=dict(os.environ, COPYFILE_DISABLE='1'))
            check = [native, '-xOf', str(partial)]
        checked_backend(check, stdout=subprocess.DEVNULL)
        after = source.stat()
        if source.is_file() and (before.st_size, before.st_mtime_ns, before.st_ino) != (after.st_size, after.st_mtime_ns, after.st_ino):
            raise Error('Source changed during compression')
        publish(partial, target)
        staging.rmdir()
    except BaseException:
        print(safe_text(('packz: incomplete output retained at ' + str(staging)).encode()), file=sys.stderr)
        raise


def pack(args):
    source = Path(args.input).absolute()
    if source.is_symlink() or not (source.is_file() or source.is_dir()):
        raise Error('Input must be a regular file or directory, not a top-level symbolic link')
    is_dir = source.is_dir()
    fmt = args.format
    codec = TAR_CODEC.get(fmt, fmt)
    container = fmt in ('zip', '7z', 'rar')
    as_tar = fmt == 'tar' or fmt in TAR_CODEC or (is_dir and not container)
    if is_dir and fmt == 'bgzip':
        raise Error('BGZF compression requires a single file')
    if container or fmt == 'tar':
        suffix = '.' + fmt
    else:
        suffix = ('.tar' if as_tar else '') + STREAM_SUFFIX[codec]
    target = Path(args.output).absolute() if args.output else source.with_name(source.name + suffix)
    if target.exists() or target.is_symlink(): raise Error('Output already exists: ' + str(target))
    if not target.parent.is_dir(): raise Error('Output parent directory does not exist')
    if is_dir and (target.parent.resolve() == source.resolve() or source.resolve() in target.parent.resolve().parents):
        raise Error('Archive output must be outside the source directory')
    if not is_dir and source.name.lower().endswith(('.gz', '.zst', '.xz', '.bz2', '.bam', '.cram', '.bcf', '.zip')):
        print('packz: input is already compressed; additional compression may save little space', file=sys.stderr)
    if as_tar and not is_dir:
        member_path(source.name)
        if source.name == '.bio-cli-incomplete':
            raise Error('Source name conflicts with the restore status marker')
    if is_dir:
        validate_pack_tree(source, portable=container)
    if container:
        pack_container(source, target, fmt, args.level)
        print(safe_text(str(target).encode('utf-8', 'replace')))
        return
    command = compressor(codec, args.threads, args.level) if fmt != 'tar' else None
    fd, name = tempfile.mkstemp(prefix=target.name + '.partial-', dir=str(target.parent))
    partial = Path(name)
    try:
        with os.fdopen(fd, 'wb') as out:
            before = None if is_dir else source.stat()
            if fmt == 'tar':
                checked_backend([tool('tar'), '-cf', '-', '-C', str(source.parent), '--', './' + source.name],
                                stdout=out, env=dict(os.environ, COPYFILE_DISABLE='1'))
            elif as_tar:
                env = os.environ.copy(); env['COPYFILE_DISABLE'] = '1'
                tar = ManagedProcess([tool('tar'), '-cf', '-', '-C', str(source.parent), '--', './' + source.name], env=env)
                try:
                    process = ManagedProcess(command, stdin=tar.stdout, stdout=out)
                    result = process.finish()
                    tar.stdout.close()
                    tarcode = tar.finish(wait_timeout=5)
                finally:
                    tar.finish(cancel=True)
                if result or tarcode: raise Error('Archive/compressor failed; partial output retained')
            else:
                with source.open('rb') as inp:
                    process = ManagedProcess(command, stdin=inp, stdout=out)
                    result = process.finish()
                if result: raise Error('Compressor failed; partial output retained')
            if before is not None:
                after = source.stat()
                if (before.st_size, before.st_mtime_ns, before.st_ino) != (after.st_size, after.st_mtime_ns, after.st_ino):
                    raise Error('Source changed during compression; partial output retained')
            out.flush(); os.fsync(out.fileno())
        if fmt == 'tar':
            check = [tool('tar'), '-tf', str(partial)]
        else:
            check = [tool('gzip' if codec == 'bgzip' else codec), '-t', str(partial)]
        if ManagedProcess(check, stdout=subprocess.DEVNULL).finish(): raise Error('Compressed stream integrity test failed')
        publish(partial, target)
    except BaseException:
        print(safe_text(('packz: incomplete output retained at ' + str(partial)).encode('utf-8', 'replace')), file=sys.stderr)
        raise
    print(safe_text(str(target).encode('utf-8', 'replace')))


def member_path(name):
    p = PurePosixPath(name)
    if p.is_absolute() or '..' in p.parts or '\\' in name or '\x00' in name:
        raise Error('Unsafe archive member path')
    return p


def extract_member(archive, member, root, directories):
    relative = member_path(member.name)
    dest = root.joinpath(*relative.parts)
    for parent in [dest] + list(dest.parents):
        if parent == root: break
        if parent.is_symlink(): raise Error('Archive member traverses a symbolic link')
    if member.isdir():
        dest.mkdir(parents=True, exist_ok=True); directories[dest] = (member.mode & 0o777, member.mtime); return
    dest.parent.mkdir(parents=True, exist_ok=True)
    if member.issym():
        link = PurePosixPath(member.linkname)
        if link.is_absolute(): raise Error('Absolute symbolic link refused')
        resolved = (dest.parent / member.linkname).resolve()
        if root != resolved and root not in resolved.parents: raise Error('Escaping symbolic link refused')
        os.symlink(member.linkname, dest)
    elif member.islnk():
        link = root.joinpath(*member_path(member.linkname).parts)
        if not link.is_file() or link.is_symlink() or root not in link.resolve().parents:
            raise Error('Invalid or forward hard link refused')
        os.link(link, dest)
    elif member.isfile():
        with archive.extractfile(member) as inp, dest.open('xb') as out:
            shutil.copyfileobj(inp, out, 65536)
        os.chmod(dest, member.mode & 0o777)
        os.utime(dest, (member.mtime, member.mtime))
    else:
        raise Error('Special device/FIFO archive member refused')


def rar_verifier():
    # Some systems install a libarchive-based unrar-free as "unrar". That
    # would repeat the same decoder instead of independently checking the RAR.
    for name in ('unrar', 'rar'):
        path = shutil.which(name)
        if path and re.search(rb'^\s*(?:UNRAR|RAR) \d+\.\d+.*Roshal', run_capture([path]).stdout, re.M):
            return path
    raise Error('--verify-rar requires RARLAB unrar or rar on PATH')


def unpack(args):
    source = regular(args.input)
    fmt = container_format(source)
    if args.verify_rar and (fmt != 'rar' or not args.directory):
        raise Error('--verify-rar requires a RAR archive and -C <new-directory>')
    if args.verify_rar:
        if any(char in str(source) for char in '*?'):
            raise Error('RAR verifier treats * and ? in archive paths as wildcards')
        verifier = rar_verifier()
        original = source.stat()
    if fmt and args.output:
        raise Error('Directory archives require -C <new-directory>')
    if args.directory or (not args.output and (fmt or source.name.lower().endswith(ARCHIVES))):
        if not args.directory: raise Error('Directory archives require -C <new-directory>')
        # Preserve absolute member names for rejection by the safe restore path.
        command = [tool('bsdtar'), '-cPf', '-', '--format', 'pax', '@' + str(source)] if fmt else None
        root = Path(args.directory).absolute()
        status = root.with_name(root.name + '.bio-cli-incomplete')
        # A sibling marker remains writable even if archive metadata makes root read-only.
        with status.open('x') as out:
            out.write('Extraction incomplete. Original archive is unchanged.\n')
        try:
            root.mkdir(parents=False, exist_ok=False)
        except BaseException:
            status.unlink()
            raise
        root = root.resolve()
        marker = root / '.bio-cli-incomplete'
        directories = {}
        member_count = 0
        expanded_bytes = 0
        try:
            marker.write_text('Extraction incomplete; see sibling status marker.\n')
            with reader(source, command) as r:
                with tarfile.open(fileobj=r.stream, mode='r|') as archive:
                    for member in iter_tar(archive):
                        member_count += 1
                        if args.max_members is not None and member_count > args.max_members:
                            raise Error('Archive member limit exceeded')
                        if member.isfile():
                            expanded_bytes += member.size
                        if args.max_output_bytes is not None and expanded_bytes > args.max_output_bytes:
                            raise Error('Expanded byte limit exceeded')
                        if member_path(member.name) == PurePosixPath('.bio-cli-incomplete'):
                            raise Error('Archive member conflicts with restore status marker')
                        extract_member(archive, member, root, directories)
                while r.stream.read(65536): pass
            if args.verify_rar:
                checked_backend([verifier, 't', '-cfg-', '-p-', '-ierr', '-idq', '--', str(source)],
                                stdout=subprocess.DEVNULL)
                latest = source.stat()
                if not os.path.samestat(original, latest) or (original.st_size, original.st_mtime_ns) != (latest.st_size, latest.st_mtime_ns):
                    raise Error('RAR source changed during restore or verification')
            marker.unlink()
            for dest in sorted(directories, key=lambda path: len(path.parts), reverse=True):
                mode, mtime = directories[dest]
                os.chmod(dest, mode)
                os.utime(dest, (mtime, mtime))
            status.unlink()
        except BaseException:
            # Best effort compatibility marker; sibling status is authoritative.
            try:
                with marker.open('x') as out:
                    out.write('Extraction incomplete; see sibling status marker.\n')
            except OSError:
                pass
            print(safe_text(('unpackz: incomplete restore; status at ' + str(status)).encode('utf-8', 'replace')), file=sys.stderr)
            raise
        if fmt == 'rar' and not args.verify_rar:
            print('unpackz: RAR decoded without an independent checksum test; use --verify-rar to require one', file=sys.stderr)
        print(safe_text(str(root).encode('utf-8', 'replace')))
    else:
        if args.max_members is not None: raise Error('--max-members requires archive directory restore with -C')
        c = compression(source)
        if c not in ('zstd', 'gzip', 'xz', 'bzip2'): raise Error('Unsupported compressed stream')
        suffix = source.suffix.lower()
        if not args.output and suffix not in ('.zst', '.gz', '.bgz', '.bgzip', '.xz', '.bz2'):
            raise Error('Use -o to name the restored file')
        target = Path(args.output).absolute() if args.output else source.with_suffix('')
        if target.exists() or target.is_symlink(): raise Error('Output already exists: ' + str(target))
        fd, name = tempfile.mkstemp(prefix=target.name + '.partial-', dir=str(target.parent))
        partial = Path(name)
        try:
            with os.fdopen(fd, 'wb') as out, reader(source) as r:
                copy_limited(r.stream, out, args.max_output_bytes)
                out.flush(); os.fsync(out.fileno())
            publish(partial, target)
        except BaseException:
            print(safe_text(('unpackz: incomplete output retained at ' + str(partial)).encode('utf-8', 'replace')), file=sys.stderr); raise
        print(safe_text(str(target).encode('utf-8', 'replace')))


def copy_limited(source, output, limit=None):
    count = 0
    while True:
        chunk = source.read(65536 if limit is None else min(65536, limit-count+1))
        if not chunk:
            return count
        count += len(chunk)
        if limit is not None and count > limit:
            raise Error('Expanded byte limit exceeded')
        output.write(chunk)


def positive_seconds(value):
    seconds = float(value)
    if not math.isfinite(seconds) or seconds <= 0:
        raise argparse.ArgumentTypeError('must be a finite positive number')
    return seconds


def positive(value):
    n = int(value)
    if n < 1: raise argparse.ArgumentTypeError('must be positive')
    return n


